import pytest
from codeownerinsights.codeowners import does_codeowner_glob_match


@pytest.mark.parametrize(
    ('path', 'glob', 'expected_result'),
    [
        (
            '/build/logs/foo/bar.log',
            '/build/logs/',
            True,
        ),
        (
            '/build/logs/foo.log',
            '/build/logs/',
            True,
        ),
        (
            '/baz/build/logs/foo/bar.log',
            '/build/logs/',
            False,
        ),
        (
            '/path/to/a/file',
            '*',
            True,
        ),
        (
            '/path/to/a/file.ext',
            '*',
            True,
        ),
        (
            'file.js',
            '*.js',
            True,
        ),
        (
            'path/to/file.js',
            '*.js',
            True,
        ),
        (
            'path/to/file.jsx',
            '*.js',
            False,
        ),
        (
            'docs/getting-started.md',
            'docs/*',
            True,
        ),
        (
            'docs/build-app/troubleshooting.md',
            'docs/*',
            False,
        ),
        (
            '/apps/github/some.file',
            '/apps/github',
            True,
        ),
        (
            '/apps/github/subfolder/some.file',
            '/apps/github',
            True,
        ),
        (
            '/logs/test.log',
            '**/logs',
            True,
        ),
        (
            '/build/logs/test.log',
            '**/logs',
            True,
        ),
        (
            '/logs/subfolder/test.log',
            '**/logs',
            True,
        ),
        # A leading slash anchors a pattern to the repository root, but the paths
        # the plugin matches against are relative to the root and carry no
        # leading slash -- so the slash-anchored form has to match relative
        # paths too. These are the cases GitHub's own CODEOWNERS docs cite.
        (
            'docs/readme.md',
            '/docs/',
            True,
        ),
        (
            'docs/sub/x.md',
            '/docs/',
            True,
        ),
        (
            'build/logs/foo/bar.log',
            '/build/logs/',
            True,
        ),
        (
            'baz/build/logs/foo.log',
            '/build/logs/',
            False,
        ),
        (
            'apps/foo.js',
            '/apps/',
            True,
        ),
        (
            'apps/github',
            '/apps/github',
            True,
        ),
        (
            'apps/github',
            '/apps/',
            True,
        ),
        (
            'apps/github',
            '/apps/github',
            True,
        ),
        (
            'docs/build-app/troubleshooting.md',
            'docs/*',
            False,
        ),
        # An unslashed directory pattern matches the directory wherever it sits
        # in the tree, not only at the root -- the same rule git's check-ignore
        # applies. The previous implementation only matched at the root.
        (
            'src/apps/foo.js',
            'apps/',
            True,
        ),
        (
            'deeply/nested/apps/foo.js',
            'apps/',
            True,
        ),
        (
            'sub/docs/readme.md',
            'docs/',
            True,
        ),
        (
            'other/docs/readme.md',
            'docs/',
            True,
        ),
        # A leading slash anchors to the root, so the same pattern does not
        # match the same directory nested elsewhere.
        (
            'src/apps/foo.js',
            '/apps/',
            False,
        ),
        (
            'sub/docs/readme.md',
            '/docs/',
            False,
        ),
        # GitHub's CODEOWNERS docs state that "[ ] to define a character range
        # doesn't work" -- brackets are matched literally, so [abc].txt only
        # matches a file literally named [abc].txt.
        (
            'a.txt',
            '[abc].txt',
            False,
        ),
        (
            'x.txt',
            '[abc].txt',
            False,
        ),
        (
            '[abc].txt',
            '[abc].txt',
            True,
        ),
        # The supported wildcards are unaffected by the literal escaping.
        (
            'path/to/file.js',
            '*.js',
            True,
        ),
        (
            'docs/sub/x.md',
            'docs/*',
            False,
        ),
        (
            'build/logs/test.log',
            '**/logs',
            True,
        ),
        # Checked against GitHub's own resolution of public repositories'
        # CODEOWNERS files. A slash in the middle anchors a pattern to the root
        # as a leading one does, and a pattern matching a directory covers
        # everything beneath it unless its last segment is a lone `*` -- where
        # GitHub, unlike git's check-ignore, does not match nested files.
        (
            'a/docs/getting-started.md',
            'docs/*',
            False,
        ),
        (
            'x/Tools/build/compute-changes.py',
            'Tools/build/compute-changes.py',
            False,
        ),
        (
            'web/source/Calculator/Service.php',
            'source/**/Calculator/',
            False,
        ),
        (
            'source/src/Engage/Calculator/Service.php',
            'source/**/Calculator/',
            True,
        ),
        (
            'build/logs/2026/app.log',
            '/build/logs',
            True,
        ),
        (
            'lib/_http_dir/sub/x.js',
            '/lib/_http_*',
            True,
        ),
        (
            'foo/zzhamtzz/sub/deeper/x.c',
            '**/*hamt*',
            True,
        ),
        (
            'lib/internal/streams/sub/x.js',
            '/lib/internal/streams/*',
            False,
        ),
        (
            'src/a.txt',
            '/*',
            False,
        ),
        (
            'README.md',
            '*.MD',
            False,
        ),
        # Wildcards match names starting with a dot, as GitHub's own
        # resolution confirms.
        (
            '.github/workflows/ci.yml',
            '*',
            True,
        ),
        (
            '.github/workflows/ci.yml',
            '*.yml',
            True,
        ),
        (
            'lib/.hidden',
            '/lib/*',
            True,
        ),
        (
            'docs/.vitepress/config.ts',
            'docs/',
            True,
        ),
    ],
)
def test_matching(path: str, glob: str, expected_result: bool) -> None:
    assert does_codeowner_glob_match(glob, path) == expected_result
